// Per-turn state note, sent after history so the static prompt stays cached.
export const stateNote = (input: {
	address?: string;
	adProducts: Array<{ id: number; name: string; price: number; stockStatus: string }>;
	cartLines: Array<{ name: string; qty: number }>;
	countryside?: boolean;
	note?: string;
	orderNumber?: string;
	paymentStatus?: string;
	phone?: string;
}): string => {
	const parts = new Intl.DateTimeFormat("en-US", {
		hour: "2-digit",
		minute: "2-digit",
		timeZone: "Asia/Ulaanbaatar",
		weekday: "long",
	}).formatToParts(new Date());
	const get = (type: string) => parts.find((p) => p.type === type)?.value ?? "";
	const cart =
		input.cartLines.length === 0
			? "хоосон"
			: input.cartLines.map((l) => `${l.name} ×${l.qty}`).join(", ");
	const order = input.orderNumber
		? `Сүүлийн захиалга: ${input.orderNumber} (${input.paymentStatus ?? "pending"})`
		: "Захиалга байхгүй";
	return [
		`Улаанбаатарын одоогийн цаг: ${get("weekday")} ${get("hour")}:${get("minute")}`,
		`Сагс: ${cart}`,
		`Утас: ${input.phone ?? "байхгүй"}. Хаяг: ${input.address ?? "байхгүй"}${input.countryside === true ? " (орон нутаг)" : ""}. Тэмдэглэл: ${input.note ?? "байхгүй"}`,
		order,
		...input.adProducts.map(
			(p) => `Дарсан зарын бараа: ${p.name} (id ${p.id}, ${p.price}₮, ${p.stockStatus})`,
		),
	].join("\n");
};
